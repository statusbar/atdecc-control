"""Fold live `?` describe metadata into the generated schema range table.

Reads the captured describe responses (captures/q1-describe-*.txt, Q1
firmware 2.10.0) and emits galaxy_schema_ranges.inc: one row per path
shape with the device's minimum/maximum/step and AEM unit code. The
C++ generator keys the table by the same shape normalization (numeric
segments -> '#', except U-Shaping band numbers, whose ranges are
per-band).

Deliberately NOT folded:
- describe 'default' fields: the device's describe 'default' is its
  generic control-DB init (e.g. every EQ band frequency "1000"),
  contradicting both the guide's tables and the observed factory state.
  Defaults are folded from captures/q1-live-dump.tsv instead — the live
  dump that corroborated the guide on 8860 of 9766 points. Where the
  dump disagrees with the guide the LIVE_DRIFT table decides: listed
  shapes are operator/venue state on the in-use LA unit (the guide
  default stands, emitted as nullptr); everything else is taken as
  firmware 2.10 factory/representative state (verified uniform across
  strips and bands where applicable).
- boolean ranges: described as minimum 'true' / maximum 'false'; the
  AEM 0/255 convention stands.
(Enum name lists ARE folded: per-shape label tables, verbatim
"value:NAME" strings as the device sends them. Alias numbers are folded
too: the device's `@N` aliases are its item indices, one per control
point, dense 0..N-1 — emitted in alias order together with each point's
human-readable name. Names are verbatim: the device's `name` and
`description` fields are identical everywhere, and about half come back
with a leading space — the firmware formats "<prefix> <label>" with an
empty prefix.)

Usage:
    fold_describes.py [--captures DIR] [--out FILE] [--check]
"""

import argparse
import ast
import pathlib
import re
import sys
from collections import defaultdict

HEADER = """\
// Copyright 2026 Jeff Koftinoff <jeff.koftinoff@statusbar.com>
// SPDX-License-Identifier: MIT
//
// GENERATED by python/galaxy/fold_describes.py — do not edit.
// Source: captures/q1-describe-*.txt (Q1, firmware 2.10.0, captured
// 2026-08-29). Shape key: numeric segments -> '#', except the band
// number after "ushaping" (per-band frequency/slope ranges).

// clang-format off
"""

# GALAXY units string -> (AEM unit multiplier, AEM UNIT_CODE_*).
UNIT_CODES = {
    "": (0, 0x00, "unitless"),
    "dB": (0, 0xB0, "UNIT_CODE_DB"),
    "dB (Peak)": (0, 0xB1, "UNIT_CODE_DB_PEAK"),
    "V": (0, 0x30, "UNIT_CODE_VOLTS"),
    "Hz": (0, 0x10, "UNIT_CODE_HERTZ"),
    "Octaves": (0, 0x13, "UNIT_CODE_OCTAVES"),
    "samples": (0, 0x0E, "UNIT_CODE_SAMPLES"),
    "sec": (0, 0x08, "UNIT_CODE_SECONDS"),
    "metres": (0, 0x18, "UNIT_CODE_METRES"),
    "%": (0, 0x02, "UNIT_CODE_PERCENT"),
    "ºK": (0, 0x20, "UNIT_CODE_KELVIN"),
}


# Shapes whose live-dump values are operator/venue state on the in-use
# unit, not factory defaults: the guide default stands (def = nullptr).
LIVE_DRIFT = {
    "/processing/input/#/mute": "externally unmuted during the 2026-08 sessions",
    "/processing/input/#/gain": "operator-moved (2 of 8 strips)",
    "/processing/matrix/#/#/gain": "venue routing (28 of 512 crosspoints)",
    "/device/input/#/mode": "operator input config (6 of 32 changed)",
    "/device/input/avb/controller_mode": "operator setting",
    "/device/preferences/display_color": "operator preference",
    "/project/snapshot/#/name": "venue project data",
    "/project/snapshot/#/comment": "venue project data",
    "/project/snapshot/#/created": "venue project data",
    "/project/snapshot/#/last_updated": "venue project data",
    "/project/snapshot/active/created": "venue project data",
    "/project/snapshot/active/last_updated": "venue project data",
    "/system/access/#/name": "venue-cleared access table (7 of 8)",
    "/system/access/#/privilege": "venue-cleared access table (7 of 8)",
}


def shape_of(path: str) -> str:
    segments = path.split("/")
    out = []
    for i, seg in enumerate(segments):
        if seg.isdigit() and not (i > 0 and segments[i - 1] == "ushaping"):
            out.append("#")
        else:
            out.append(seg)
    return "/".join(out)


def parse_number(text):
    try:
        return float(text)
    except (TypeError, ValueError):
        return None


def collect(captures_dir: pathlib.Path):
    entries = {}
    for f in sorted(captures_dir.glob("q1-describe-*.txt")):
        for line in f.read_text().splitlines():
            line = line.strip()
            if line.startswith("?"):
                line = line[1:]
            if not line:
                continue
            try:
                d = ast.literal_eval(line)
            except (ValueError, SyntaxError):
                continue
            entries.update(d)

    shapes = defaultdict(set)
    units_seen = defaultdict(set)
    for path, meta in entries.items():
        lo = parse_number(meta.get("minimum"))
        hi = parse_number(meta.get("maximum"))
        step = parse_number(meta.get("step"))
        if lo is None or hi is None or step is None or not lo < hi:
            continue  # boolean/string/unranged point
        unit = meta.get("units", "")
        if unit not in UNIT_CODES:
            print(f"error: unmapped units {unit!r} at {path}", file=sys.stderr)
            sys.exit(1)
        shape = shape_of(path)
        shapes[shape].add((lo, hi, step))
        units_seen[shape].add(unit)

    enums = {}
    for path, meta in entries.items():
        labels = meta.get("enum")
        if not labels:
            continue
        shape = shape_of(path)
        if shape in enums and enums[shape] != labels:
            print(f"error: non-uniform enum for shape {shape}", file=sys.stderr)
            sys.exit(1)
        enums[shape] = labels

    aliases = {}
    names = {}
    for path, meta in entries.items():
        alias = meta.get("alias", "")
        if not re.fullmatch(r"@\d+", alias):
            print(
                f"error: missing/malformed alias at {path}: {alias!r}", file=sys.stderr
            )
            sys.exit(1)
        aliases[path] = int(alias[1:])
        if meta.get("name") != meta.get("description"):
            print(
                f"error: name != description at {path}: "
                f"{meta.get('name')!r} vs {meta.get('description')!r}",
                file=sys.stderr,
            )
            sys.exit(1)
        names[path] = meta["name"]
    if sorted(aliases.values()) != list(range(len(aliases))):
        print("error: alias numbers are not dense 0..N-1", file=sys.stderr)
        sys.exit(1)

    dump = {}
    for line in (captures_dir / "q1-live-dump.tsv").read_text().splitlines():
        if not line.strip():
            continue
        path, _, value = line.partition("\t")
        dump[path] = value
    if set(dump) != set(entries):
        print(
            "error: live-dump paths do not match the describe captures", file=sys.stderr
        )
        sys.exit(1)
    unknown_drift = set(LIVE_DRIFT) - {shape_of(p) for p in dump}
    if unknown_drift:
        print(
            f"error: LIVE_DRIFT shapes not in the namespace: {sorted(unknown_drift)}",
            file=sys.stderr,
        )
        sys.exit(1)
    # Identity and telemetry are never defaults either: /entity/* names the
    # dumped unit and /status/* is a snapshot of its moment (clock locks,
    # network addresses, connected talkers, log line). The guide's template
    # values stand for both, so the shipped schema describes no particular
    # unit or venue.
    defaults = {
        p: None
        if shape_of(p) in LIVE_DRIFT or p.startswith(("/entity/", "/status/"))
        else v
        for p, v in dump.items()
    }

    rows = []
    for shape in sorted(shapes):
        ranges = shapes[shape]
        units = units_seen[shape]
        if len(ranges) != 1 or len(units) != 1:
            print(
                f"error: non-uniform metadata for shape {shape}: {sorted(ranges)} {sorted(units)}",
                file=sys.stderr,
            )
            sys.exit(1)
        (lo, hi, step) = next(iter(ranges))
        unit = next(iter(units))
        rows.append((shape, lo, hi, step, unit))
    return rows, enums, aliases, names, defaults


def fmt(v: float) -> str:
    text = f"{v:.6f}".rstrip("0").rstrip(".")
    return text if "." in text or "e" in text else text + ".0"


def render_enums(enums) -> str:
    out = []
    names = {}
    for i, shape in enumerate(sorted(enums)):
        names[shape] = f"GALAXY_ENUM_{i}"
        out.append(
            f"inline constexpr char const* {names[shape]}[{len(enums[shape])}] = {{\n"
        )
        for label in enums[shape]:
            assert "'" not in label and "\\" not in label and '"' not in label, label
            out.append(f'    "{label}",\n')
        out.append("};\n")
    out.append(
        "\nstruct GalaxyEnum\n{\n    char const* shape;\n    std::uint16_t count;\n"
        "    char const* const* labels;\n};\n\n"
    )
    out.append(f"inline constexpr GalaxyEnum GALAXY_ENUMS[{len(enums)}] = {{\n")
    for shape in sorted(enums):
        out.append(f'    {{"{shape}", {len(enums[shape])}, {names[shape]}}},\n')
    out.append("};\n")
    return "".join(out)


def render_aliases(aliases, names, defaults) -> str:
    by_alias = sorted((n, p) for p, n in aliases.items())
    out = [
        "\n// The device's control points in alias order: GALAXY_ALIASES[n] is\n"
        "// the path whose device alias is @n, with its verbatim human-readable\n"
        "// name (identical `name`/`description` describe fields; leading spaces\n"
        "// are the device's own formatting) and the live-dump default. A null\n"
        "// default marks curated LIVE_DRIFT (operator/venue state on the\n"
        "// in-use unit): the guide default in the template table stands.\n"
        "struct GalaxyAliasEntry\n{\n    char const* path;\n    char const* name;\n    char const* def;\n};\n\n"
    ]
    out.append(
        f"inline constexpr GalaxyAliasEntry GALAXY_ALIASES[{len(by_alias)}] = {{\n"
    )
    for _, path in by_alias:
        name = names[path]
        default = defaults[path]
        assert '"' not in path and "\\" not in path, path
        assert '"' not in name and "\\" not in name, name
        if default is None:
            rendered = "nullptr"
        else:
            escaped = default.replace("\\", "\\\\").replace('"', '\\"')
            rendered = f'"{escaped}"'
        out.append(f'    {{"{path}", "{name}", {rendered}}},\n')
    out.append("};\n")
    return "".join(out)


def render(rows) -> str:
    out = [HEADER]
    out.append(
        "struct GalaxyRange\n{\n    char const* shape;\n    double min;\n    double max;\n    double step;\n"
        "    std::int8_t unit_multiplier;\n    std::uint8_t unit_code;\n};\n\n"
    )
    out.append(f"inline constexpr GalaxyRange GALAXY_RANGES[{len(rows)}] = {{\n")
    for shape, lo, hi, step, unit in rows:
        mult, code, name = UNIT_CODES[unit]
        out.append(
            f'    {{"{shape}", {fmt(lo)}, {fmt(hi)}, {fmt(step)}, {mult}, 0x{code:02X}}},  // {name}\n'
        )
    out.append("};\n")
    return "".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    root = pathlib.Path(__file__).resolve().parents[2]
    ap.add_argument("--captures", default=str(root / "captures"))
    ap.add_argument(
        "--out",
        default=str(
            root / "statusbar" / "controlplane_devices" / "galaxy_schema_ranges.inc"
        ),
    )
    ap.add_argument(
        "--check",
        action="store_true",
        help="verify the committed table matches the captures",
    )
    args = ap.parse_args()

    rows, enums, aliases, names, defaults = collect(pathlib.Path(args.captures))
    text = (
        render(rows)
        + "\n"
        + render_enums(enums)
        + render_aliases(aliases, names, defaults)
        + "// clang-format on\n"
    )
    out = pathlib.Path(args.out)
    if args.check:
        if not out.exists() or out.read_text() != text:
            print(
                f"STALE: {out} does not match the captures; re-run fold_describes.py",
                file=sys.stderr,
            )
            return 1
        print(f"OK: {out.name} matches the captures ({len(rows)} ranged shapes)")
        return 0
    out.write_text(text)
    print(f"{out}: {len(rows)} ranged shapes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
